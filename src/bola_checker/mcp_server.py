"""Local, authorization-first MCP interface for BOLACheck.

The MCP transport is deliberately a very small adapter around :class:`MCPService`.
All useful behaviour lives in the service so it can be tested without FastMCP,
an MCP client, or network access.  FastMCP is imported only when a caller asks
to construct the stdio server; installing the optional ``mcp`` extra is not
required for the rest of the package.

The service keeps credentials in an in-memory :class:`CredentialVault`.  Tool
arguments can name an environment variable, but can never contain a secret
value.  Persistent state receives only the opaque fingerprint generated by
``StateStore``.
"""

from __future__ import annotations

import hashlib
import inspect
import re
from collections.abc import Callable, Iterable, Sequence
from dataclasses import dataclass, field, replace
from pathlib import Path
from typing import Annotated, Any, Literal, Protocol, cast

from pydantic import Field

from bola_checker.capture import CaptureError, parse_har_records
from bola_checker.credentials import CredentialVault
from bola_checker.endpoints import (
    build_test_targets,
    correlate_ownership,
    discover_endpoint_candidates,
    templatize,
)
from bola_checker.models import (
    CredentialKind,
    ProbeMode,
    ProbeResult,
    RequestRecord,
)
from bola_checker.reporting import ReportBundle, write_reports
from bola_checker.scope import ScopeError, ScopeGuard
from bola_checker.state import PendingCombination, StateStore, object_ref_fingerprint

MAX_PATH_LENGTH = 4096
MAX_IDENTITY_LENGTH = 128
MAX_RECORDS = 10_000
MAX_PLAN_ITEMS = 500
MAX_ENV_NAME_LENGTH = 128
_SAFE_IDENTIFIER = frozenset("abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789_.-")
_SAFE_ENDPOINT = re.compile(r"/(?:[A-Za-z0-9._~!$&'()*+,;:@%{}-]+/?)*\Z")
_SAFE_HTTP_METHOD = re.compile(r"[A-Z]{1,10}\Z")

# These aliases are used only on the optional MCP wrappers.  FastMCP can then
# publish bounded JSON schemas while the service layer still performs the
# authoritative validation for non-MCP callers.
MCPPath = Annotated[str, Field(min_length=1, max_length=MAX_PATH_LENGTH)]
MCPIdentity = Annotated[str, Field(min_length=1, max_length=MAX_IDENTITY_LENGTH)]
MCPName = Annotated[str, Field(min_length=1, max_length=MAX_IDENTITY_LENGTH)]
MCPEnvironmentName = Annotated[str, Field(min_length=1, max_length=MAX_ENV_NAME_LENGTH)]


class MCPServiceError(ValueError):
    """A bounded, user-safe error raised by the service layer."""


class PendingExecutor(Protocol):
    """Dependency-injected deterministic executor boundary.

    The MCP service never imports or constructs an HTTP client.  Phase 5 can
    implement this protocol, while tests can provide a pure fake.
    """

    def run_pending(
        self,
        pending: Sequence[PendingCombination],
        *,
        base_url: str,
        scope_guard: ScopeGuard,
        state_store: StateStore,
        credential_vault: CredentialVault,
        run_id: int,
        mode: ProbeMode,
    ) -> Sequence[ProbeResult]: ...


ExecutorCallable = Callable[..., Sequence[ProbeResult]]


@dataclass
class MCPSession:
    """Mutable process-local state for one local MCP process."""

    scope_guard: ScopeGuard | None = None
    scope_path: Path | None = None
    state_store: StateStore | None = None
    credential_vault: CredentialVault = field(default_factory=CredentialVault)
    records: list[RequestRecord] = field(default_factory=list)
    identity_hints: dict[str, str] = field(default_factory=dict)
    # State may persist opaque object references.  Keep a process-local map so
    # an injected executor can reconstruct the concrete ID from current,
    # already-sanitized traffic without putting it in MCP output or SQLite.
    object_ids: dict[tuple[str, str, str], str] = field(default_factory=dict, repr=False)
    outcomes: list[ProbeResult] = field(default_factory=list)
    last_base_url: str | None = None


def _bounded_text(value: object, field_name: str, *, max_length: int) -> str:
    if not isinstance(value, str) or not value.strip() or len(value) > max_length:
        raise MCPServiceError(f"{field_name} is missing or exceeds its limit")
    if any(ord(character) < 32 or ord(character) == 127 for character in value):
        raise MCPServiceError(f"{field_name} contains a control character")
    return value


def _safe_identity(value: object) -> str:
    identity = _bounded_text(value, "identity", max_length=MAX_IDENTITY_LENGTH)
    if any(character not in _SAFE_IDENTIFIER for character in identity):
        raise MCPServiceError("identity contains unsupported characters")
    return identity


def _safe_path(value: object, field_name: str = "path") -> Path:
    if isinstance(value, Path):
        text = _bounded_text(str(value), field_name, max_length=MAX_PATH_LENGTH)
    else:
        text = _bounded_text(value, field_name, max_length=MAX_PATH_LENGTH)
    path = Path(text)
    if not path.is_absolute():
        raise MCPServiceError(f"{field_name} must be an absolute local path")
    return path


def _safe_env_name(value: object) -> str:
    name = _bounded_text(value, "environment variable", max_length=MAX_ENV_NAME_LENGTH)
    if not name.replace("_", "").isalnum() or not (name[0].isalpha() or name[0] == "_"):
        raise MCPServiceError("environment variable name is invalid")
    return name


def _safe_kind(value: object) -> CredentialKind:
    if not isinstance(value, str):
        raise MCPServiceError("credential kind is invalid")
    try:
        return CredentialKind(value.casefold())
    except ValueError as error:
        raise MCPServiceError("credential kind is invalid") from error


def _safe_result(result: ProbeResult) -> dict[str, Any]:
    """Return structural outcome metadata without identifiers or bodies."""

    endpoint_template = _safe_result_endpoint(result.target.endpoint_template)
    method = result.target.method
    if not isinstance(method, str) or _SAFE_HTTP_METHOD.fullmatch(method) is None:
        raise MCPServiceError("executor returned an invalid endpoint method")
    return {
        "attacker_status": result.attacker_status,
        "endpoint_template": endpoint_template,
        "method": method,
        "owner_status": result.owner_status,
        "retryable": result.retryable,
        "verdict": result.verdict.value,
    }


def _safe_result_endpoint(value: str) -> str:
    """Canonicalize a result route and reject URL/secret-shaped output."""

    if (
        not isinstance(value, str)
        or len(value) > 512
        or not value.startswith("/")
        or any(character.isspace() or ord(character) < 32 for character in value)
        or any(marker in value for marker in ("://", "?", "#", "\\", "//"))
        or re.search(r"%(?![0-9A-Fa-f]{2})", value) is not None
        or re.search(r"%(?:2[eEfF]|5[cC])", value) is not None
    ):
        raise MCPServiceError("executor returned an invalid endpoint template")
    # Endpoint discovery is the canonical route normalizer used by phase 4;
    # it replaces supported concrete identifier segments with placeholders.
    canonical = templatize(value)
    if not _SAFE_ENDPOINT.fullmatch(canonical):
        raise MCPServiceError("executor returned an invalid endpoint template")
    return canonical


class MCPService:
    """Pure service handlers backing both tests and the optional MCP server."""

    def __init__(
        self,
        session: MCPSession | None = None,
        *,
        executor: PendingExecutor | ExecutorCallable | None = None,
    ) -> None:
        self.session = session or MCPSession()
        self.executor = executor

    def _require_ready(self) -> tuple[ScopeGuard, StateStore]:
        guard = self.session.scope_guard
        store = self.session.state_store
        if guard is None:
            raise MCPServiceError("load_scope must succeed before this operation")
        if store is None:
            raise MCPServiceError("init_state must succeed before this operation")
        return guard, store

    def _clear_session_data(self) -> None:
        """Drop all engagement-derived data before a scope/state transition."""

        self.session.records.clear()
        self.session.identity_hints.clear()
        self.session.object_ids.clear()
        self.session.outcomes.clear()
        self.session.last_base_url = None
        self.session.credential_vault = CredentialVault()
        self.executor = None

    def load_scope(self, scope_path: str | Path) -> dict[str, Any]:
        """Load a real, provenance-marked scope file; failures clear the session."""

        self._clear_session_data()
        self.session.scope_guard = None
        self.session.scope_path = None
        self.session.state_store = None
        try:
            path = _safe_path(scope_path, "scope_path")
        except MCPServiceError as error:
            return {"ok": False, "error": "scope_denied", "message": str(error)}
        try:
            guard = ScopeGuard.from_file(path)
        except ScopeError as error:
            return {"ok": False, "error": "scope_denied", "message": str(error)}
        self.session.scope_guard = guard
        self.session.scope_path = path
        return {
            "ok": True,
            "client": guard.config.client_name,
            "allowed_hosts": list(guard.config.allowed_hosts),
            "authorization_reference_fingerprint": _fingerprint(
                guard.config.authorization_reference
            ),
        }

    def init_state(self, db_path: str | Path) -> dict[str, Any]:
        """Open the local append-only state database."""

        self._clear_session_data()
        self.session.state_store = None
        try:
            path = _safe_path(db_path, "db_path")
        except MCPServiceError as error:
            return {"ok": False, "error": "state_unavailable", "message": str(error)}
        try:
            store = StateStore(path)
        except (OSError, ValueError, RuntimeError) as error:
            return {"ok": False, "error": "state_unavailable", "message": str(error)}
        self.session.state_store = store
        return {"ok": True, "schema_version": store.schema_version()}

    def register_environment_credential(
        self, identity: str, kind: str, name: str, environment_variable: str
    ) -> dict[str, Any]:
        """Register an opaque ``env:NAME`` reference; no secret value is accepted."""

        identity_value = _safe_identity(identity)
        name_value = _bounded_text(name, "credential name", max_length=MAX_IDENTITY_LENGTH)
        variable = _safe_env_name(environment_variable)
        credential_kind = _safe_kind(kind)
        _guard, store = self._require_ready()
        reference = self.session.credential_vault.environment_reference(
            identity=identity_value,
            kind=credential_kind,
            name=name_value,
            variable=variable,
        )
        store.add_identity(identity_value, credential=reference)
        return {
            "ok": True,
            "identity": identity_value,
            "kind": credential_kind.value,
            "name": name_value,
            "reference_registered": True,
        }

    def import_har(self, har_path: str | Path, identity: str) -> dict[str, Any]:
        """Import already-sanitized HAR records after checking every URL is scoped."""

        guard, store = self._require_ready()
        path = _safe_path(har_path, "har_path")
        identity_value = _safe_identity(identity)
        try:
            records = parse_har_records(path, identity_value)
            if len(records) > MAX_RECORDS:
                raise CaptureError("HAR contains too many records")
            for record in records:
                guard.require_allowed(record.url, record.method)
        except (CaptureError, ScopeError) as error:
            return {"ok": False, "error": "import_denied", "message": str(error)}

        self.session.records.extend(records)
        if len(self.session.records) > MAX_RECORDS:
            self.session.records = self.session.records[:MAX_RECORDS]
        store.add_identity(identity_value)
        for candidate in discover_endpoint_candidates(records):
            self.session.object_ids[
                (
                    candidate.endpoint_template,
                    candidate.method,
                    object_ref_fingerprint(candidate.object_id),
                )
            ] = candidate.object_id
        return {
            "ok": True,
            "identity": identity_value,
            "records_imported": len(records),
            # HAR import already redacts all transport credentials.  A future
            # live extractor may add references, but never through this tool's
            # arguments.
            "credential_references": 0,
            "identity_hints": 0,
            "body_secret_warnings": 0,
        }

    def plan_endpoints(self) -> dict[str, Any]:
        """Discover candidates and persist only strong, unambiguous ownership."""

        _guard, store = self._require_ready()
        candidates = discover_endpoint_candidates(self.session.records)
        correlations = correlate_ownership(self.session.records, self.session.identity_hints)
        persisted = build_test_targets(store, correlations)
        # Object identifiers are intentionally not returned by an MCP tool.
        structural_candidates = [
            {
                "endpoint_template": candidate.endpoint_template,
                "method": candidate.method,
                "location": candidate.location.value,
                "id_field": candidate.id_field,
            }
            for candidate in candidates[:MAX_PLAN_ITEMS]
        ]
        return {
            "ok": True,
            "candidates": structural_candidates,
            "candidate_count": len(candidates),
            "ownership_persisted": len(persisted.persisted),
            "ownership_conflicts": len(persisted.conflicts),
        }

    def plan_tests(self) -> dict[str, Any]:
        """Return a bounded structural view of pending owner/attacker work."""

        _guard, store = self._require_ready()
        pending = store.untested_combinations()
        endpoints = {item["id"]: item for item in store.list_endpoints()}
        identities = {item["id"]: item for item in store.list_identities()}
        items = []
        for combination in pending[:MAX_PLAN_ITEMS]:
            endpoint = endpoints.get(combination.endpoint_id)
            owner = identities.get(combination.owner_identity_id)
            attacker = identities.get(combination.attacker_identity_id)
            if endpoint is None or owner is None or attacker is None:
                continue
            items.append(
                {
                    "endpoint_template": endpoint["template"],
                    "method": endpoint["method"],
                    "owner_identity": owner["name"],
                    "attacker_identity": attacker["name"],
                    "mode": ProbeMode.READ.value,
                }
            )
        return {"ok": True, "pending_count": len(pending), "items": items}

    def run_pending_tests(
        self,
        base_url: str,
        executor: PendingExecutor | ExecutorCallable | None = None,
        *,
        mode: ProbeMode | str = ProbeMode.READ,
    ) -> dict[str, Any]:
        """Run pending tests through an injected executor after a fresh scope check."""

        guard, store = self._require_ready()
        active_executor = executor or self.executor
        if active_executor is None:
            raise MCPServiceError("run_pending_tests requires an injected executor")
        base = _bounded_text(base_url, "base_url", max_length=MAX_PATH_LENGTH)
        try:
            probe_mode = mode if isinstance(mode, ProbeMode) else ProbeMode(str(mode).casefold())
        except ValueError as error:
            raise MCPServiceError("probe mode is invalid") from error
        if probe_mode is not ProbeMode.READ:
            raise MCPServiceError("MCP execution is read-only; mutation probes are unavailable")
        # This is intentionally repeated for every run, including a read run.
        try:
            guard.require_allowed(base, "GET")
        except ScopeError as error:
            return {"ok": False, "error": "scope_denied", "message": str(error)}

        pending = tuple(store.untested_combinations())
        endpoint_by_id = {item["id"]: item for item in store.list_endpoints()}
        executor_pending_list: list[PendingCombination] = []
        for combination in pending:
            object_reference = _pending_object(combination)
            concrete_object = self.session.object_ids.get(
                (
                    str(endpoint_by_id.get(combination.endpoint_id, {}).get("template", "")),
                    str(endpoint_by_id.get(combination.endpoint_id, {}).get("method", "")),
                    object_reference,
                )
            )
            if concrete_object is None:
                if object_reference.startswith("obj_"):
                    raise MCPServiceError(
                        "pending object reference has no current in-memory concrete mapping"
                    )
                concrete_object = object_reference
            executor_pending_list.append(_replace_pending_object(combination, concrete_object))
        executor_pending = tuple(executor_pending_list)
        # State's persistent metadata schema is intentionally narrow.  The
        # mode and count stay in the returned, non-secret handler result rather
        # than widening the audit JSON allowlist from this adapter.
        run_id = store.start_run("mcp-run")
        results = _invoke_executor(
            active_executor,
            executor_pending,
            base_url=base,
            scope_guard=guard,
            state_store=store,
            credential_vault=self.session.credential_vault,
            run_id=run_id,
            mode=probe_mode,
        )
        for result in results:
            if not isinstance(result, ProbeResult):
                raise MCPServiceError("executor returned an invalid probe result")
            store.record_probe_result(result, run_id=run_id)
        self.session.outcomes.extend(results)
        self.session.last_base_url = base
        return {
            "ok": True,
            "run_id": run_id,
            "pending_count": len(pending),
            "results": [_safe_result(result) for result in results],
        }

    def generate_report(self, output_dir: str | Path) -> dict[str, Any]:
        """Render deterministic reports from the current session outcomes."""

        guard, store = self._require_ready()
        directory = _safe_path(output_dir, "output_dir")
        bundle = ReportBundle.from_outcomes(
            findings=store.list_findings(),
            outcomes=tuple(self.session.outcomes),
            scope_target_label=guard.config.client_name,
            authorization_reference=guard.config.authorization_reference,
            # Include work still pending in the denominator.  A report with
            # no findings must not accidentally imply all planned combinations
            # were executed.
            total_combinations=len(self.session.outcomes) + len(store.untested_combinations()),
        )
        paths = write_reports(bundle, output_dir=directory)
        return {"ok": True, "reports": {kind: str(path) for kind, path in paths.items()}}


def _invoke_executor(
    executor: PendingExecutor | ExecutorCallable,
    pending: Sequence[PendingCombination],
    **kwargs: Any,
) -> tuple[ProbeResult, ...]:
    """Invoke either the phase-5 protocol or a plain callable fake."""

    runner = getattr(executor, "run_pending", None)
    if runner is None:
        if not callable(executor):
            raise MCPServiceError("executor does not expose run_pending")
        runner = executor
    try:
        result = runner(pending, **kwargs)
    except (ScopeError, OSError, TimeoutError) as error:
        raise MCPServiceError("executor failed during the scoped run") from error
    if inspect.isawaitable(result):
        raise MCPServiceError("asynchronous executors are not supported by this sync MCP handler")
    if isinstance(result, (str, bytes)) or not isinstance(result, Iterable):
        raise MCPServiceError("executor returned an invalid result collection")
    return tuple(cast(Iterable[ProbeResult], result))


def _fingerprint(value: str) -> str:
    return "sha256:" + hashlib.sha256(value.encode("utf-8")).hexdigest()


def _pending_object(combination: PendingCombination) -> str:
    """Read either the pre-migration object_id or current object_ref field."""

    value = getattr(combination, "object_ref", None)
    if isinstance(value, str):
        return value
    value = getattr(combination, "object_id", None)
    if isinstance(value, str):
        return value
    raise MCPServiceError("state returned a pending combination without an object reference")


def _replace_pending_object(
    combination: PendingCombination, object_value: str
) -> PendingCombination:
    """Preserve compatibility across the StateStore object_ref migration."""

    return replace(combination, object_ref=object_value)


def create_mcp_server(
    service: MCPService | None = None,
    *,
    executor: PendingExecutor | ExecutorCallable | None = None,
) -> Any:
    """Create the optional FastMCP stdio server, importing FastMCP lazily."""

    try:
        from fastmcp import FastMCP  # type: ignore[import-not-found]
    except ImportError as error:  # pragma: no cover - optional dependency
        raise MCPServiceError("FastMCP is unavailable; install bolacheck[mcp].") from error

    active = service or MCPService(executor=executor)
    if service is not None and executor is not None:
        active.executor = executor
    server = FastMCP("bolacheck")

    @server.tool  # type: ignore[untyped-decorator]
    def load_scope(scope_path: MCPPath) -> dict[str, Any]:
        return active.load_scope(scope_path)

    @server.tool  # type: ignore[untyped-decorator]
    def init_state(db_path: MCPPath) -> dict[str, Any]:
        return active.init_state(db_path)

    @server.tool  # type: ignore[untyped-decorator]
    def register_environment_credential(
        identity: MCPIdentity,
        kind: Literal["bearer", "header", "cookie"],
        name: MCPName,
        environment_variable: MCPEnvironmentName,
    ) -> dict[str, Any]:
        return active.register_environment_credential(identity, kind, name, environment_variable)

    @server.tool  # type: ignore[untyped-decorator]
    def import_har(har_path: MCPPath, identity: MCPIdentity) -> dict[str, Any]:
        return active.import_har(har_path, identity)

    @server.tool  # type: ignore[untyped-decorator]
    def plan_endpoints() -> dict[str, Any]:
        return active.plan_endpoints()

    @server.tool  # type: ignore[untyped-decorator]
    def plan_tests() -> dict[str, Any]:
        return active.plan_tests()

    @server.tool  # type: ignore[untyped-decorator]
    def run_pending_tests(
        base_url: MCPPath,
        mode: Literal["read"] = "read",
    ) -> dict[str, Any]:
        try:
            return active.run_pending_tests(
                base_url,
                mode=mode,
            )
        except MCPServiceError as error:
            return {"ok": False, "error": "execution_denied", "message": str(error)}

    @server.tool  # type: ignore[untyped-decorator]
    def generate_report(output_dir: MCPPath) -> dict[str, Any]:
        return active.generate_report(output_dir)

    return server


def main() -> None:  # pragma: no cover - exercised by an MCP host
    create_mcp_server().run(transport="stdio")


if __name__ == "__main__":  # pragma: no cover
    main()
